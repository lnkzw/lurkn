/// A chat badge, already resolved to an image.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct Badge {
    pub set_id: String,
    pub version: String,
    /// UNTRUSTED: comes from Twitch's badge metadata.
    pub title: String,
    /// Twitch's per-badge detail. For `subscriber` and `founder` it is the number
    /// of months subscribed, which is the only place that number is published —
    /// `helix/subscriptions` is broadcaster-only and does not carry a duration.
    /// Empty for every other badge.
    pub info: String,
    /// `None` until the badge sets have been fetched and the reference resolved.
    /// The renderer skips unresolved badges rather than showing a broken image.
    pub url_1x: Option<Url>,
    pub url_2x: Option<Url>,
    pub url_4x: Option<Url>,
}

impl Badge {
    /// A badge carried by a message before its images are known.
    pub fn unresolved(set_id: String, version: String, info: String) -> Self {
        Self {
            set_id,
            version,
            title: String::new(),
            info,
            url_1x: None,
            url_2x: None,
            url_4x: None,
        }
    }

    pub fn is_resolved(&self) -> bool {
        self.url_1x.is_some()
    }
}

/// An RGB colour, as Twitch sends for usernames.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct Rgb {
    pub r: u8,
    pub g: u8,
    pub b: u8,
}

impl Rgb {
    /// Parse `#RRGGBB`. Twitch sends an empty string for users who never picked one.
    pub fn parse(hex: &str) -> Option<Self> {
        let hex = hex.strip_prefix('#')?;
        if hex.len() != 6 || !hex.bytes().all(|b| b.is_ascii_hexdigit()) {
            return None;
        }
        Some(Self {
            r: u8::from_str_radix(&hex[0..2], 16).ok()?,
            g: u8::from_str_radix(&hex[2..4], 16).ok()?,
            b: u8::from_str_radix(&hex[4..6], 16).ok()?,
        })
    }

    pub fn to_css(self) -> String {
        format!("#{:02x}{:02x}{:02x}", self.r, self.g, self.b)
    }
}

/// One piece of a parsed message. The renderer never sees raw text to interpret.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum ChatToken {
    Text {
        text: String,
    },
    /// Boxed: an `Emote` is several times the size of the other variants, and a
    /// message is mostly text tokens.
    Emote {
        emote: Box<Emote>,
    },
    /// Scheme already validated as http/https in Rust.
    Link {
        url: Url,
        display: String,
    },
    Mention {
        /// Carried so a mention can open the same user card a name in the log
        /// does. Twitch sends it on the fragment; nothing here has to guess it.
        id: UserId,
        login: Login,
        display: String,
    },
}

