#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct ChatMessage {
    pub id: MessageId,
    pub channel_id: UserId,
    pub author: ChatAuthor,
    /// Parsed in Rust; the UI renders tokens, never a string.
    pub tokens: Vec<ChatToken>,
    /// UNTRUSTED. Kept for copy and search, never rendered as markup.
    pub raw_text: String,
    #[serde(with = "time::serde::rfc3339")]
    #[specta(type = String)]
    pub sent_at: OffsetDateTime,
    pub kind: MessageKind,
    pub state: MessageState,
    /// Set when this message replies to another.
    pub reply_to: Option<MessageId>,
    /// Set when this line is a channel event rather than plain chat, or when an
    /// ordinary message came with bits attached.
    #[serde(default)]
    pub event: Option<ChannelEvent>,
    /// Names the reader, or matches one of their highlight rules.
    ///
    /// Decided once, where the settings are, rather than in the renderer: the
    /// notification and the marked row must agree, and two implementations of
    /// the same rule eventually will not.
    #[serde(default)]
    pub highlighted: bool,
    /// The tint the matching rule asked for. `None` with `highlighted` set
    /// means the accent, as for being named.
    #[serde(default)]
    pub highlight_color: Option<Rgb>,
}

/// Whether a message names the reader or matches one of their words.
///
/// Matching is case-insensitive and on whole words, so `ann` does not fire on
/// "announcement" and a login inside a URL does not count. A message the reader
/// sent themselves never highlights — they know what they said.
pub fn mentions(text: &str, login: &str, display_name: &str, keywords: &[String]) -> bool {
    let haystack = text.to_lowercase();

    let mut needles: Vec<String> = Vec::with_capacity(keywords.len() + 2);
    if !login.is_empty() {
        needles.push(login.to_lowercase());
    }
    let display = display_name.to_lowercase();
    if !display.is_empty() && !needles.contains(&display) {
        needles.push(display);
    }
    for word in keywords {
        let word = word.trim().to_lowercase();
        if !word.is_empty() {
            needles.push(word);
        }
    }

    needles
        .iter()
        .any(|needle| contains_word(&haystack, needle))
}

/// A whole-word search over already-lowercased text.
///
/// "Word" means: not flanked by a letter or digit. Punctuation around a name is
/// normal in chat — `@forsen,` and `forsen:` are both someone being addressed.
fn contains_word(haystack: &str, needle: &str) -> bool {
    if needle.is_empty() {
        return false;
    }

    let mut from = 0;
    while let Some(found) = haystack[from..].find(needle) {
        let start = from + found;
        let end = start + needle.len();

        let before_ok = haystack[..start]
            .chars()
            .next_back()
            .is_none_or(|c| !c.is_alphanumeric());
        let after_ok = haystack[end..]
            .chars()
            .next()
            .is_none_or(|c| !c.is_alphanumeric());

        if before_ok && after_ok {
            return true;
        }
        // Advance past this occurrence; a needle can appear more than once and
        // only one of them need stand alone.
        from = end;
    }

    false
}

/// Deterministic username colour for chatters who never picked one.
///
/// Twitch's own default palette, indexed by a stable hash of the login, so a user
/// keeps the same colour across sessions and channels.
pub fn fallback_color(login: &Login) -> Rgb {
    const PALETTE: [Rgb; 15] = [
        Rgb {
            r: 0xFF,
            g: 0x00,
            b: 0x00,
        },
        Rgb {
            r: 0x00,
            g: 0x00,
            b: 0xFF,
        },
        Rgb {
            r: 0x00,
            g: 0x80,
            b: 0x00,
        },
        Rgb {
            r: 0xB2,
            g: 0x22,
            b: 0x22,
        },
        Rgb {
            r: 0xFF,
            g: 0x7F,
            b: 0x50,
        },
        Rgb {
            r: 0x9A,
            g: 0xCD,
            b: 0x32,
        },
        Rgb {
            r: 0xFF,
            g: 0x45,
            b: 0x00,
        },
        Rgb {
            r: 0x2E,
            g: 0x8B,
            b: 0x57,
        },
        Rgb {
            r: 0xDA,
            g: 0xA5,
            b: 0x20,
        },
        Rgb {
            r: 0xD2,
            g: 0x69,
            b: 0x1E,
        },
        Rgb {
            r: 0x5F,
            g: 0x9E,
            b: 0xA0,
        },
        Rgb {
            r: 0x1E,
            g: 0x90,
            b: 0xFF,
        },
        Rgb {
            r: 0xFF,
            g: 0x69,
            b: 0xB4,
        },
        Rgb {
            r: 0x8A,
            g: 0x2B,
            b: 0xE2,
        },
        Rgb {
            r: 0x00,
            g: 0xFF,
            b: 0x7F,
        },
    ];

    let sum: u32 = login.as_str().bytes().map(u32::from).sum();
    PALETTE[(sum as usize) % PALETTE.len()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_a_hex_colour() {
        assert_eq!(Rgb::parse("#FF0000"), Some(Rgb { r: 255, g: 0, b: 0 }));
        assert_eq!(
            Rgb::parse("#1e90ff"),
            Some(Rgb {
                r: 30,
                g: 144,
                b: 255
            })
        );
    }

    #[test]
    fn rejects_anything_that_is_not_a_hex_colour() {
        // Twitch sends "" for chatters who never chose one.
        for bad in [
            "", "#FFF", "FF0000", "#GGGGGG", "#FF00000", "red", "#FF00 0",
        ] {
            assert_eq!(Rgb::parse(bad), None, "should have rejected {bad:?}");
        }
    }

    #[test]
    fn round_trips_through_css() {
        assert_eq!(Rgb::parse("#1e90ff").unwrap().to_css(), "#1e90ff");
    }

    #[test]
    fn the_fallback_colour_is_stable_per_user() {
        let a = Login::parse("forsen").unwrap();
        let b = Login::parse("forsen").unwrap();
        assert_eq!(fallback_color(&a), fallback_color(&b));
    }

    #[test]
    fn different_users_can_get_different_fallback_colours() {
        let logins = ["alpha", "bravo", "charlie", "delta", "echo", "foxtrot"];
        let colors: std::collections::HashSet<_> = logins
            .iter()
            .map(|l| fallback_color(&Login::parse(l).unwrap()))
            .collect();
        assert!(colors.len() > 1, "the palette should spread users out");
    }
}

/// A channel's chat restrictions.
///
/// EventSub only reports *changes*, so the initial state comes from Helix's
/// `Get Chat Settings` when the channel is joined.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct RoomState {
    pub emote_only: bool,
    pub subscriber_only: bool,
    pub unique_only: bool,
    /// `Some(minutes)` when followers-only is on; `Some(0)` means any follower.
    pub follower_only_minutes: Option<u32>,
    /// `Some(seconds)` when slow mode is on.
    pub slow_mode_seconds: Option<u32>,
}

impl RoomState {
    pub fn is_unrestricted(&self) -> bool {
        *self == Self::default()
    }

    /// Short labels for the chat header, in the order they should read.
    pub fn labels(&self) -> Vec<String> {
        let mut out = Vec::new();

        if self.emote_only {
            out.push("Emote only".to_owned());
        }
        if self.subscriber_only {
            out.push("Subs only".to_owned());
        }
        match self.follower_only_minutes {
            Some(0) => out.push("Followers only".to_owned()),
            Some(minutes) if minutes % 60 == 0 && minutes >= 60 => {
                out.push(format!("Followers {}h+", minutes / 60));
            }
            Some(minutes) => out.push(format!("Followers {minutes}m+")),
            None => {}
        }
        if let Some(seconds) = self.slow_mode_seconds {
            out.push(format!("Slow {seconds}s"));
        }
        if self.unique_only {
            out.push("Unique only".to_owned());
        }

        out
    }
}

#[cfg(test)]
mod room_state_tests {
    use super::*;

    #[test]
    fn an_unrestricted_room_has_no_labels() {
        let state = RoomState::default();
        assert!(state.is_unrestricted());
        assert!(state.labels().is_empty());
    }

    #[test]
    fn followers_only_reads_naturally_at_every_duration() {
        let at = |minutes| RoomState {
            follower_only_minutes: Some(minutes),
            ..Default::default()
        };
        assert_eq!(at(0).labels(), ["Followers only"]);
        assert_eq!(at(10).labels(), ["Followers 10m+"]);
        assert_eq!(at(60).labels(), ["Followers 1h+"]);
        assert_eq!(at(1440).labels(), ["Followers 24h+"]);
        // Not a whole number of hours, so minutes stay.
        assert_eq!(at(90).labels(), ["Followers 90m+"]);
    }

    #[test]
    fn every_restriction_is_listed_in_reading_order() {
        let state = RoomState {
            emote_only: true,
            subscriber_only: true,
            unique_only: true,
            follower_only_minutes: Some(30),
            slow_mode_seconds: Some(5),
        };
        assert_eq!(
            state.labels(),
            [
                "Emote only",
                "Subs only",
                "Followers 30m+",
                "Slow 5s",
                "Unique only"
            ]
        );
        assert!(!state.is_unrestricted());
    }

    #[test]
    fn slow_mode_alone_is_reported() {
        let state = RoomState {
            slow_mode_seconds: Some(30),
            ..Default::default()
        };
        assert_eq!(state.labels(), ["Slow 30s"]);
    }
}

#[cfg(test)]
mod highlight_tests {
    use super::mentions;

    fn words(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn a_plain_message_does_not_highlight() {
        assert!(!mentions("hello chat", "lurker", "lurker", &[]));
    }

    #[test]
    fn being_named_highlights_however_it_is_punctuated() {
        assert!(mentions("@lurker hi", "lurker", "lurker", &[]));
        assert!(mentions("lurker: hi", "lurker", "lurker", &[]));
        assert!(mentions("hi lurker, ok?", "lurker", "lurker", &[]));
        assert!(mentions("HI LURKER", "lurker", "lurker", &[]));
    }

    /// A login is also a substring of longer words, and those are not you.
    #[test]
    fn a_name_inside_a_longer_word_does_not_highlight() {
        assert!(!mentions(
            "lurkero is someone else",
            "lurker",
            "lurker",
            &[]
        ));
        assert!(!mentions("xlurker", "lurker", "lurker", &[]));
    }

    /// The first occurrence may be embedded while a later one stands alone.
    #[test]
    fn a_later_standalone_match_still_counts() {
        assert!(mentions("xlurker and lurker", "lurker", "lurker", &[]));
    }

    #[test]
    fn a_display_name_that_differs_from_the_login_also_counts() {
        assert!(mentions("hey Lurky", "lurker", "Lurky", &[]));
    }

    #[test]
    fn keywords_are_matched_the_same_way() {
        assert!(mentions(
            "anyone up for poe?",
            "lurker",
            "lurker",
            &words(&["poe"])
        ));
        assert!(!mentions(
            "poem night",
            "lurker",
            "lurker",
            &words(&["poe"])
        ));
        assert!(!mentions(
            "nothing here",
            "lurker",
            "lurker",
            &words(&["poe"])
        ));
    }

    #[test]
    fn blank_keywords_and_names_are_ignored() {
        assert!(!mentions("something", "", "", &words(&["", "   "])));
    }
}
