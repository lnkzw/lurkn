/// What kind of channel event a message carries, for styling and for the
/// "show channel events" setting. The wording itself is Twitch's; see
/// [`ChannelEvent::text`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub enum ChannelEventKind {
    /// A new subscription, paid or Prime.
    Sub,
    /// A renewal, with the months the subscriber has stacked up.
    Resub,
    /// One sub given to one named viewer.
    SubGift,
    /// A batch of subs given to the channel at large.
    CommunityGift,
    /// A gift or Prime sub continued as a paid one, or passed on.
    Upgrade,
    Raid,
    /// Bits, which ride along with an ordinary message rather than replacing it.
    Cheer,
    Announcement,
    Charity,
    BitsBadge,
    /// A notice type this build has no styling for. Twitch's text still renders.
    Other,
}

/// A channel event delivered alongside chat: a sub, a gift, a raid, bits.
///
/// The wording is Twitch's own `system_message` rather than something assembled
/// here. Twitch localises it, keeps it in step with new notice types, and phrases
/// the awkward cases ("X gifted 5 subs, they've given 173 in the channel!")
/// correctly. Rebuilding that from the structured fields would be a worse copy
/// of a string already in the payload.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct ChannelEvent {
    pub kind: ChannelEventKind,
    /// UNTRUSTED: Twitch's rendering, carrying display names. Never markup.
    /// Empty for a cheer, where the chatter's own message is the line.
    pub text: String,
    /// The one number worth emphasising for this kind: bits cheered, viewers
    /// raided with, subs gifted, months resubscribed.
    pub count: Option<u32>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
